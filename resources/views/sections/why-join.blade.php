<script>
document.querySelectorAll('.modern-benefit-toggle').forEach(function (button) {

    button.addEventListener('click', function () {

        const benefit = button.closest('.modern-benefit');

        const isOpen = benefit.classList.contains('active');


        /*
         * Close all benefits
         */
        document.querySelectorAll('.modern-benefit').forEach(function (item) {

            item.classList.remove('active');

            item.querySelector('.benefit-icon').textContent = '+';

        });


        /*
         * Open clicked benefit
         */
        if (!isOpen) {

            benefit.classList.add('active');

            benefit.querySelector('.benefit-icon').textContent = '−';

        }

    });

});
</script>