        <p>We may use the information collected to:</p>
        <ul>
            <li>Process and assess membership applications.</li>
            <li>Conduct KYC and business verification.</li>
            <li>Verify company information and business activity.</li>
            <li>Verify business references.</li>
            <li>Create and maintain Member profiles.</li>
            <li>Provide membership services and benefits.</li>
            <li>Facilitate relevant business introductions and opportunities.</li>
            <li>Connect Members with relevant trade or logistics requirements.</li>
            <li>Understand Members' business interests and requirements.</li>
            <li>Identify relevant opportunities and potential business connections.</li>
            <li>Bring relevant non-member businesses and enquiries into the FreightConnect platform.</li>
            <li>Communicate regarding membership, services and opportunities.</li>
            <li>Administer membership payments and accounts.</li>
            <li>Maintain the security and integrity of FreightConnect.</li>
            <li>Comply with applicable legal and regulatory requirements.</li>
        </ul>
