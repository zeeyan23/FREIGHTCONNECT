        <p>As part of this process, we may verify:</p>
        <ul>
            <li>Company registration and legal/business information.</li>
            <li>Business licences and relevant authorisations.</li>
            <li>Evidence of genuine business activity.</li>
            <li>Information provided in the application.</li>
            <li>Business references.</li>
        </ul>
