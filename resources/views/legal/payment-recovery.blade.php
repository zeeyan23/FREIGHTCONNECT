<section class="legal-section" id="annual-fee">

    <h2>
        <span>8.</span>
        Annual Participation Fee
    </h2>

    <div class="legal-fee-box">

        <span>ANNUAL PARTICIPATION FEE</span>

        <strong>USD 300</strong>

