{{-- 1. Purpose --}}
<section class="legal-section" id="purpose">

    <h2>
        <span>1.</span>
        Purpose
    </h2>

    <p>
        FreightConnect Member Payment Recovery Support is designed to assist eligible Freight-Forwarding Members in recovering certain unpaid invoices arising from genuine business transactions with other FreightConnect Freight-Forwarding Members.
    </p>

    <p>
        Where the conditions of this programme are met, FreightConnect may provide limited payment support against an eligible unpaid amount.
    </p>

</section>


{{-- 2. Eligibility --}}
<section class="legal-section" id="eligibility">

    <h2>
        <span>2.</span>
        Eligibility
    </h2>

    <p>
        The programme is available only to <strong>Freight-Forwarding Members who have opted into Member Payment Recovery Support.</strong>
    </p>

    <p>
        An eligible claim must:
    </p>

    <ul>
        <li>
            Arise from a genuine business transaction between
            <strong>two active FreightConnect Freight-Forwarding Members.</strong>
        </li>

        <li>
            Relate to an unpaid invoice issued for services actually provided.
        </li>

        <li>
            Be <strong>reported to FreightConnect within 30 days from the date the invoice was issued.</strong>
        </li>

        <li>
            Involve a debtor who has entered
            <strong>formal insolvency proceedings.</strong>
        </li>

        <li>
            Be supported by the required transaction and payment documentation.
        </li>

        <li>
            Satisfy all other conditions of this programme.
        </li>
    </ul>

    <div class="legal-notice-box">

        <i class="fa-solid fa-circle-exclamation"></i>

        <div>
            <strong>Important</strong>

            <p>
                Trade Partners are not covered under Member Payment Recovery Support.
            </p>
        </div>

    </div>

</section>


{{-- 3. Recovery Process --}}
<section class="legal-section" id="recovery-process">

    <h2>
        <span>3.</span>
        Recovery Process
    </h2>

    <p>
        When an eligible invoice becomes unpaid, the affected member must notify FreightConnect and provide the relevant documentation.
    </p>

    <p>
        FreightConnect will then make <strong>up to three documented attempts to obtain payment from the debtor.</strong>
    </p>

    <p>
        If the invoice remains unpaid and the debtor has entered formal insolvency proceedings, FreightConnect will assess the matter under the Member Payment Recovery Support programme.
    </p>

</section>


{{-- 4. Payment Support --}}
<section class="legal-section" id="payment-support">

    <h2>
        <span>4.</span>
        Payment Support
    </h2>

    <p>
        For an approved eligible claim:
    </p>

    <div class="legal-highlight-grid">

        <div class="legal-highlight-card">

            <span>SUPPORT</span>

            <strong>30%</strong>

            <p>
                of the eligible unpaid invoice
            </p>

        </div>


        <div class="legal-highlight-card">

            <span>MAXIMUM SUPPORT</span>

            <strong>USD 3,000</strong>

            <p>
                per member per membership year
            </p>

        </div>

    </div>

    <p>
        The maximum of USD 3,000 applies to the <strong>combined support provided to a member during one membership year</strong>, regardless of the number of eligible claims.
    </p>

</section>


{{-- 5. Example --}}
<section class="legal-section" id="example">

    <h2>
        <span>5.</span>
        Example
    </h2>

    <p>
        If an eligible member has an unpaid invoice of <strong>USD 5,000</strong> and the debtor subsequently enters formal insolvency:
    </p>

    <div class="legal-calculation">

        <span>USD 5,000 × 30%</span>

        <strong>= USD 1,500</strong>

    </div>

    <p>
        The eligible payment support would therefore be <strong>USD 1,500</strong>.
    </p>

    <p>
        If the unpaid invoice is <strong>USD 12,000</strong>:
    </p>

    <div class="legal-calculation">

        <span>USD 12,000 × 30%</span>

        <strong>= USD 3,600</strong>

    </div>

    <p>
        However, the maximum payment support available is
        <strong>USD 3,000 per membership year.</strong>
    </p>

</section>


{{-- 6. Documentation --}}
<section class="legal-section" id="documentation">

    <h2>
        <span>6.</span>
        Required Documentation
    </h2>

    <p>
        The member may be required to provide:
    </p>

    <ul>
        <li>Copy of the unpaid invoice</li>

        <li>Proof of the underlying transaction</li>

        <li>Service completion or shipment records, where applicable</li>

        <li>Relevant quotations, bookings or agreements</li>

        <li>Payment follow-up correspondence</li>

        <li>Evidence of the debtor’s formal insolvency</li>

        <li>
            Any additional documentation reasonably required
            to assess the claim
        </li>
    </ul>

</section>


{{-- 7. Not Covered --}}
<section class="legal-section" id="not-covered">

    <h2>
        <span>7.</span>
        Situations Not Covered
    </h2>

    <p>
        Member Payment Recovery Support does not apply to:
    </p>

    <ul>
        <li>
            Unpaid invoices owed by <strong>Trade Partners.</strong>
        </li>

        <li>
            Transactions involving non-members.
        </li>

        <li>
            Ordinary late payments where formal insolvency has not occurred.
        </li>

        <li>
            Commercial disputes or disagreements regarding services,
            pricing, quality or contractual obligations where insolvency
            is not the cause of non-payment.
        </li>

        <li>
            Fraudulent, fictitious or deliberately misrepresented transactions.
        </li>

        <li>
            Amounts exceeding the programme’s applicable limits.
        </li>

        <li>
            <strong>
                Invoices not reported to FreightConnect within 30 days
                from the invoice issue date.
            </strong>
        </li>

        <li>
            Claims submitted outside the prescribed claim period.
        </li>

        <li>
            Transactions that do not satisfy the programme’s
            eligibility requirements.
        </li>
    </ul>

</section>


