    </p>

</section>


{{-- 9. Claim Assessment --}}
<section class="legal-section" id="claim-assessment">

    <h2>
        <span>9.</span>
        Claim Assessment
    </h2>

    <p>
        Every claim is subject to review by FreightConnect.
    </p>

    <p>
        Submission of a claim does not automatically create an
        entitlement to payment support. FreightConnect may request
        additional information or documentation before making its
        determination.
    </p>

</section>


{{-- 10. Limit --}}
<section class="legal-section" id="limit">

    <h2>
        <span>10.</span>
        Limit of Support
    </h2>

    <p>
        Member Payment Recovery Support is limited to
        <strong>30% of the eligible unpaid invoice</strong>, subject
        to the <strong>USD 3,000 maximum annual support limit per member.</strong>
    </p>

    <p>
        The programme does not provide full recovery of unpaid invoices.
    </p>

</section>


